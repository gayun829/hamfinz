const out = P.map((p, i) => {
  if (p.raw) {
    const pos = i % 4;
    const opts = [...p.raw.slice(1)];
    opts.splice(pos, 0, p.raw[0]);
    return { id: p.id, question: p.question, options: opts, correctIndex: pos, explanation: p.explanation };
  }
  const pos = i % 4;
  const opts = p.wrong.map(p.fmt);
  opts.splice(pos, 0, p.fmt(p.answer));
  return { id: p.id, question: p.question, options: opts, correctIndex: pos, explanation: p.explanation.replace('{A}', p.fmt(p.answer)) };
});

